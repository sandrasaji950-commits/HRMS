# SECURITY WARNING: keep the secret key used in production secret!
# Secure resolution: environment variable -> local file -> random generator (with severe warning log)
def get_secret_key():
    if os.getenv('DJANGO_SECRET_KEY'):
        return os.getenv('DJANGO_SECRET_KEY')
    secret_file = BASE_DIR / 'secret_key.txt'
    if os.path.exists(secret_file):
        with open(secret_file, 'r') as f:
            return f.read().strip()
    logging.warning("DJANGO_SECRET_KEY environment variable and secret_key.txt not found. Generating an ephemeral secret key for development!")
    # Generate and save a key locally for session consistency in development
    ephemeral_key = secrets.token_hex(32)
    try:
        with open(secret_file, 'w') as f:
            f.write(ephemeral_key)
    except IOError:
        pass
    return ephemeral_key

SECRET_KEY = get_secret_key()

